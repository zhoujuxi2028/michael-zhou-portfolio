import { TOOL_VERSION } from '../version.ts';

/** One generated test case: run `file` (relative to the test file) and check `ruleId` fires as expected. */
export interface CaseTestEntry {
  caseId: string;
  ruleId: string;
  file: string;
  window?: [number, number];
  expectTriggered: boolean;
  description?: string;
}

export interface RenderOptions {
  /** describe() title. */
  title: string;
  /** Module specifier of `src/casegen/case-runner.ts`, relative to the generated test file. */
  runnerImport: string;
}

/**
 * Render a standalone Vitest file for the given cases. Each case must run clean
 * (no data quality issues) and fire `ruleId` exactly when `expectTriggered` is true.
 */
export function renderCaseTest(entries: readonly CaseTestEntry[], opts: RenderOptions): string {
  const spec = (p: string) => (p.startsWith('.') ? p : `./${p}`);
  return `// Generated by adas-lab ${TOOL_VERSION}. Do not edit; regenerate instead.
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { runCaseFile } from ${JSON.stringify(spec(opts.runnerImport))};

interface Case { caseId: string; ruleId: string; file: string; window?: [number, number]; expectTriggered: boolean; description?: string }

const cases: Case[] = ${JSON.stringify(entries, null, 2)};

describe(${JSON.stringify(opts.title)}, () => {
  it.each(cases)('$caseId', async (c) => {
    const result = await runCaseFile(fileURLToPath(new URL(c.file, import.meta.url)), { window: c.window });
    expect(result.dataQualityIssues).toBe(0);
    expect(result.firedRules.includes(c.ruleId)).toBe(c.expectTriggered);
  });
});
`;
}
